/**
 * Clase de entidad que representa a Tipodoc dentro del dominio de la aplicación.
 * Se utiliza para mapear la estructura de datos.
 */
export class Tipodoc {
  /**
     * Propiedad de la entidad que representa id tipodoc.
     * Contiene un valor de tipo: number.
     */
    id_tipodoc: number;
  /**
     * Propiedad de la entidad que representa nombre documento.
     * Contiene un valor de tipo: string.
     */
    nombre_documento: string;
  /**
     * Propiedad de la entidad que representa abreviatura.
     * Contiene un valor de tipo: string.
     */
    abreviatura: string;
}
